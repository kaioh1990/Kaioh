"""Generate src/core/opcodes.h from Ikemen GO's bytecode.go so opcode
numbers in cooked content match exactly.

usage: python3 gen_opcodes.py path/to/bytecode.go > src/core/opcodes.h"""
import re, sys

src = open(sys.argv[1]).read().split('\n')
blocks = []  # (first name, [names])
i = 0
while i < len(src):
    m = re.match(r'\t(OC_\w+) OpCode = iota', src[i])
    if m:
        names = [m.group(1)]
        i += 1
        while i < len(src) and not src[i].startswith(')'):
            line = src[i].split('//')[0].strip()
            if line:
                if not re.match(r'^OC_\w+$', line):
                    raise SystemExit('unexpected line in const block: %r' % src[i])
                names.append(line)
            i += 1
        blocks.append(names)
    i += 1
out = ['// Generated by tools/gen/gen_opcodes.py from Ikemen GO bytecode.go. Do not edit.',
       '#ifndef CVF_OPCODES_H', '#define CVF_OPCODES_H', '']
for names in blocks:
    out.append('enum {')
    for k, n in enumerate(names):
        out.append('    %s = %d,' % (n, k))
    out.append('};')
    out.append('')
out.append('#endif')
print('\n'.join(out))
sys.stderr.write('blocks: %s\n' % [len(b) for b in blocks])
