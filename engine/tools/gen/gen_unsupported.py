#!/usr/bin/env python3
"""Placeholders for standard-library / platform functions the translated
game references but the native runtime does not provide yet (netplay, HTTP,
JSON, XML, dialogs...). Each returns zero values; error results carry
"<name>: not supported by the native engine yet".

usage: gen_unsupported.py [--allow LIST [--update]] ik_sim.h out.c obj.o...
(runtime objects whose defined symbols are excluded)

--allow LIST: fail (exit 1, nothing written) when a placeholder is needed
that LIST (tools/gen/unsupported_allowed.txt) does not name, so new library
calls never turn into silent stubs. --update rewrites LIST instead."""
import re, subprocess, sys

args = sys.argv[1:]
allow, update = None, False
if args[:1] == ['--allow']:
    allow, args = args[1], args[2:]
    if args[:1] == ['--update']:
        update, args = True, args[1:]
hdr, out, objs = args[0], args[1], args[2:]
defined = set()
for o in objs:
    r = subprocess.run(['nm', '-g', '--defined-only', o], capture_output=True, text=True)
    for ln in r.stdout.splitlines():
        f = ln.split()
        if len(f) >= 3:
            defined.add(f[2].lstrip('_') if sys.platform == 'darwin' else f[2])

text = open(hdr).read()
sec = text.split('// std-library entry points')[1].split('// package variables')[0]
lines = []
for ln in sec.splitlines():
    m = re.match(r'^(.+?)\b([A-Za-z_][A-Za-z0-9_]*)\((.*)\);\s*//(.*)$', ln)
    if not m:
        continue
    ret, name, args, comment = m.group(1).strip(), m.group(2), m.group(3), m.group(4).strip()
    if name in defined:
        continue
    ret = re.sub(r'/\*.*?\*/', '', ret).strip()
    if ret == 'void':
        body = ''
    elif ret == 'GoIface' and 'error' in comment.split(')')[-1]:
        body = f' return go_errorf("{name}: not supported by the native engine yet");'
    elif ret.startswith('Ret_') and comment.rstrip().endswith('error)'):
        body = (f' {ret} r; memset(&r, 0, sizeof r); r.r{comment.count(",", comment.rfind("(")) } = '
                f'go_errorf("{name}: not supported by the native engine yet"); return r;')
    else:
        body = f' {ret} r; memset(&r, 0, sizeof r); return r;'
    lines.append(f'{ret} {name}({args}) {{{body} }} // {comment}')

names = {}
for ln in lines:
    m = re.match(r'^(.+?)\b([A-Za-z_][A-Za-z0-9_]*)\((.*)\) \{.*\} // (.*)$', ln)
    names[m.group(2)] = m.group(4).strip()
if allow:
    listed = {l.split('#')[0].strip() for l in open(allow) if l.split('#')[0].strip()}
    new = sorted(set(names) - listed)
    if update:
        head = [l for l in open(allow) if l.startswith('#')]
        with open(allow, 'w') as f:
            f.write(''.join(head) + ''.join(f'{n}  # {names[n]}\n' for n in sorted(names)))
    elif new:
        sys.stderr.write('gen_unsupported: %d new placeholder(s) not in %s:\n' % (len(new), allow))
        for n in new:
            sys.stderr.write(f'  {n}  // {names[n]}\n')
        sys.stderr.write('Implement them in a runtime file (src/ik), or allow them deliberately '
                         '(regen.sh with ALLOW_NEW_PLACEHOLDERS=1).\n')
        sys.exit(1)
    gone = sorted(listed - set(names))
    if gone and not update:
        print('no longer placeholders (remove from %s): %s' % (allow, ' '.join(gone)))

with open(out, 'w') as f:
    f.write('// Generated by tools/gen/gen_unsupported.py. Do not edit: implement the\n'
            '// function in a runtime file instead and regenerate.\n'
            '#include <string.h>\n#include "ik/ik_sim.h"\n\n')
    f.write('\n'.join(sorted(lines)) + '\n')
print(f'{len(lines)} unsupported functions')
