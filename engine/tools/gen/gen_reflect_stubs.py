#!/usr/bin/env python3
"""Writes src/ik/ik_reflect_stubs.c: panicking stand-ins for the reflect
entry points declared in the generated ik_sim.h that ik_reflect.c does not
implement. Usage: gen_reflect_stubs.py ik_sim.h ik_reflect.c out.c"""
import re, sys
h = open(sys.argv[1]).read()
impl = open(sys.argv[2]).read()
sys.argv[2] = sys.argv[3]
out = ['// Generated by tools/gen/gen_reflect_stubs.py. Do not edit.',
       '// reflect entry points not implemented by ik_reflect.c.',
       '#include "ik/ik_sim.h"', '']
for line in h.split('\n'):
    m = re.match(r'^(.*?) (reflect_\w+)\((.*)\); //', line)
    if not m:
        continue
    ret, name, params = m.groups()
    if re.search(r'\b' + name + r'\(', impl):
        continue
    ps = [] if params == 'void' else [p.rsplit(' ', 1)[1] for p in params.split(', ')]
    body = ' '.join('(void)%s;' % p for p in ps)
    if ret == 'void':
        out.append('%s %s(%s) { %s go_panic_str("%s: not implemented"); }' % (ret, name, params, body, name))
    else:
        out.append('%s %s(%s) { %s go_panic_str("%s: not implemented"); }' % (ret, name, params, body, name))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
