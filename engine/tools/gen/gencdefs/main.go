// gencdefs: emit C declarations (constants, structs) for Ikemen GO types,
// using go/types. usage: gencdefs SRCDIR OUT_CONSTS OUT_TYPES Type1 Type2 ...
package main

import (
	"fmt"
	"go/ast"
	"go/build"
	"go/constant"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var pkg *types.Package

func main() {
	dir := os.Args[1]
	ctx := build.Default
	ctx.BuildTags = []string{"vita"}
	if t, ok := os.LookupEnv("GOTOC_TAGS"); ok { // build configuration (default: vita)
		ctx.BuildTags = strings.Fields(strings.ReplaceAll(t, ",", " "))
	}
	ctx.CgoEnabled = true
	bp, _ := ctx.ImportDir(dir, 0)
	fset := token.NewFileSet()
	var files []*ast.File
	for _, f := range append(bp.GoFiles, bp.CgoFiles...) {
		af, err := parser.ParseFile(fset, filepath.Join(dir, f), nil, 0)
		if err == nil {
			files = append(files, af)
		}
	}
	conf := types.Config{FakeImportC: true, Importer: newImporter(fset), Error: func(error) {}}
	pkg, _ = conf.Check("main", fset, files, nil)
	ownPkgs[pkg] = true

	// ---- constants
	var cs []string
	sc := pkg.Scope()
	names := sc.Names()
	sort.Strings(names)
	for _, n := range names {
		c, ok := sc.Lookup(n).(*types.Const)
		if !ok {
			continue
		}
		if strings.HasPrefix(n, "OC_") {
			continue // opcodes.h
		}
		v := c.Val()
		switch v.Kind() {
		case constant.Int:
			if i, ok := constant.Int64Val(v); ok {
				if i >= -2147483648 && i <= 2147483647 {
					cs = append(cs, fmt.Sprintf("#define %s (%d)", n, i))
				} else {
					cs = append(cs, fmt.Sprintf("#define %s ((i64)%dLL)", n, i))
				}
			} else if u, ok := constant.Uint64Val(v); ok {
				cs = append(cs, fmt.Sprintf("#define %s ((u64)%dULL)", n, u))
			}
		case constant.Float:
			f, _ := constant.Float64Val(v)
			cs = append(cs, fmt.Sprintf("#define %s (%s)", n, fmtFloat(f)))
		}
	}
	out := "// Generated by tools/gen/gencdefs from Ikemen GO. Do not edit.\n#ifndef CVF_GEN_CONSTS_H\n#define CVF_GEN_CONSTS_H\n\n" + strings.Join(cs, "\n") + "\n\n#endif\n"
	os.WriteFile(os.Args[2], []byte(out), 0o644)

	// ---- types
	if b, err := os.ReadFile(os.Getenv("GENCDEFS_OVERRIDES")); err == nil {
		for _, ln := range strings.Split(string(b), "\n") {
			f := strings.Fields(ln)
			if len(f) >= 2 && !strings.HasPrefix(ln, "#") {
				overrides[f[0]] = strings.Join(f[1:], " ")
			}
		}
	}
	want := os.Args[4:]
	if len(want) == 1 && want[0] == "ALL" {
		want = nil
		for _, n := range sc.Names() {
			if tn, ok := sc.Lookup(n).(*types.TypeName); ok && !tn.IsAlias() {
				if _, isNamed := tn.Type().(*types.Named); isNamed {
					if tn.Type().(*types.Named).TypeParams() == nil {
						want = append(want, n)
						typeByName[n] = tn.Type()
					}
				}
			}
		}
	}
	emitted := map[string]bool{}
	var order []string
	var visit func(n string)
	deps := map[string][]string{}
	for len(want) > 0 {
		n := want[0]
		want = want[1:]
		if emitted[n] {
			continue
		}
		emitted[n] = true
		if _, ok := overrides[n]; ok {
			continue
		}
		obj := lookupT(n)
		if obj == nil {
			fmt.Fprintln(os.Stderr, "no type", n)
			continue
		}
		order = append(order, n)
		if st, ok := obj.Underlying().(*types.Struct); ok {
			for i := 0; i < st.NumFields(); i++ {
				for _, d := range namedDeps(st.Field(i).Type()) {
					deps[n] = append(deps[n], d)
					want = append(want, d)
				}
			}
		} else {
			for _, d := range namedDeps(obj.Underlying()) {
				deps[n] = append(deps[n], d)
				want = append(want, d)
			}
		}
	}
	_ = visit
	// topological order by value-embedding (pointers don't need order)
	done := map[string]bool{}
	var sorted []string
	var topo func(n string)
	topo = func(n string) {
		if done[n] {
			return
		}
		done[n] = true
		obj := lookupT(n)
		if obj != nil {
			for _, d := range valueDeps(obj.Underlying()) {
				topo(d)
			}
		}
		sorted = append(sorted, n)
	}
	sort.Strings(order)
	for _, n := range order {
		topo(n)
	}
	var keep []string
	for _, n := range sorted {
		if _, ok := overrides[n]; !ok {
			keep = append(keep, n)
		}
	}
	sorted = keep
	var b strings.Builder
	b.WriteString("// Generated by tools/gen/gencdefs from Ikemen GO. Do not edit.\n#ifndef CVF_GEN_TYPES_H\n#define CVF_GEN_TYPES_H\n\n#include \"core/gort.h\"\n\n")
	for _, n := range sorted {
		obj := lookupT(n)
		if _, ok := obj.Underlying().(*types.Struct); ok {
			fmt.Fprintf(&b, "typedef struct %s %s;\n", n, n)
		}
	}
	b.WriteString("\n")
	var body strings.Builder
	bb := &body
	var plainNamed, sliceNamed []string
	for _, n := range sorted {
		obj := lookupT(n)
		switch u := obj.Underlying().(type) {
		case *types.Struct:
			for i := 0; i < u.NumFields(); i++ {
				ensureAnon(bb, u.Field(i).Type())
				ensureArrs(bb, u.Field(i).Type())
				if es, ok := u.Field(i).Type().Underlying().(*types.Struct); ok && u.Field(i).Embedded() {
					for k := 0; k < es.NumFields(); k++ {
						ensureArrs(bb, es.Field(k).Type())
					}
				}
			}
			fmt.Fprintf(bb, "struct %s {\n", n)
			writeFields(bb, u)
			bb.WriteString("};\n\n")
		default:
			if nt, ok := obj.(*types.Named); ok {
				if lay, ok := bindTypedef(nt); ok { // binding type declared as a C type
					plainNamed = append(plainNamed, fmt.Sprintf("typedef %s %s;\n", lay, n))
					continue
				}
			}
			if _, isSlice := u.(*types.Slice); isSlice {
				sliceNamed = append(sliceNamed, fmt.Sprintf("typedef %s;\n", cdecl(u, n)))
			} else {
				plainNamed = append(plainNamed, fmt.Sprintf("typedef %s;\n", cdecl(u, n)))
			}
		}
	}
	var mn0 []string
	for n := range mapTypes {
		mn0 = append(mn0, n)
	}
	sort.Strings(mn0)
	for _, n := range mn0 {
		fmt.Fprintf(&b, "#ifndef CVF_DEF_%s\n#define CVF_DEF_%s\ntypedef GoMap %s; /* %s */\n#endif\n", n, n, n, types.TypeString(mapTypes[n], qual))
	}
	var an []string
	for n := range arrTypes {
		an = append(an, n)
	}
	sort.Strings(an)
	for _, n := range an { // before named types whose underlying type is an array
		fmt.Fprintf(&b, "#ifndef CVF_DEF_%s\n#define CVF_DEF_%s\ntypedef struct %s %s;\n#endif\n", n, n, n, n)
	}
	for _, t := range plainNamed {
		b.WriteString(t)
	}

	for _, n := range anonOrder {
		fmt.Fprintf(&b, "typedef struct %s %s;\n", n, n)
	}
	// slice and map typedefs (element types may be incomplete: pointers only)
	var sn []string
	for n := range sliceTypes {
		sn = append(sn, n)
	}
	sort.Strings(sn)
	// slices in dependency order: a slice of a named slice type needs that
	// type's typedef first
	namedSliceDone := map[string]bool{}
	sliceDone := map[string]bool{}
	pendingNamed := map[string]string{}
	for _, t := range sliceNamed {
		f := strings.Fields(strings.TrimSuffix(strings.TrimSpace(t), ";"))
		pendingNamed[f[len(f)-1]] = t
	}
	for progress := true; progress; {
		progress = false
		for _, n := range sn {
			if sliceDone[n] {
				continue
			}
			el := cbase(sliceTypes[n])
			dep := strings.TrimRight(el, "*")
			if _, isNamedSlice := pendingNamed[dep]; isNamedSlice && !namedSliceDone[dep] {
				continue
			}
			if _, isSlice := sliceTypes[dep]; isSlice && !sliceDone[dep] {
				continue
			}
			fmt.Fprintf(&b, "#ifndef CVF_DEF_%s\n#define CVF_DEF_%s\ntypedef struct { %s *p; int len, cap; } %s;\n#endif\n", n, n, el, n)
			sliceDone[n] = true
			progress = true
		}
		for name, t := range pendingNamed {
			if namedSliceDone[name] {
				continue
			}
			f := strings.Fields(t)
			if len(f) >= 2 && sliceDone[f[1]] {
				b.WriteString(t)
				namedSliceDone[name] = true
				progress = true
			}
		}
	}
	b.WriteString("\n")
	// typedefs for any struct body not forward-declared yet
	for _, ln := range strings.Split(body.String(), "\n") {
		if strings.HasPrefix(ln, "struct ") && strings.HasSuffix(ln, " {") {
			n := strings.TrimSuffix(strings.TrimPrefix(ln, "struct "), " {")
			if !strings.HasPrefix(n, "Anon_") {
				fmt.Fprintf(&b, "#ifndef CVF_TD_%s\n#define CVF_TD_%s\ntypedef struct %s %s;\n#endif\n", n, n, n, n)
			}
		}
	}
	b.WriteString(body.String())
	var restArr strings.Builder
	for _, n := range an {
		ensureArrs(&restArr, arrTypes[n])
	}
	for _, n := range anonOrder {
		ensureAnon(&restArr, anonStructs[n])
	}
	b.WriteString(restArr.String())
	// helper instantiations (need complete element types)
	for _, n := range sn {
		el := cbase(sliceTypes[n])
		if strings.HasPrefix(el, "void") || strings.Contains(el, "/*") {
			continue
		}
		mac := "GO_SLICE_FUNCS"
		if pointerFree(sliceTypes[n]) {
			mac = "GO_SLICE_FUNCS_A"
		}
		fmt.Fprintf(&b, "#ifndef CVF_FN_%s\n#define CVF_FN_%s\n%s(%s, %s)\n#endif\n", n, n, mac, n, el)
	}
	for _, n := range mn0 {
		mt := mapTypes[n]
		k, v := cbase(mt.Key()), cbase(mt.Elem())
		if strings.Contains(k+v, "/*") || k == "void" || v == "void" {
			continue
		}
		sk := "false"
		if isStringT(mt.Key()) {
			sk = "true"
		}
		if types.IsInterface(mt.Key()) {
			sk = "2" // interface keys: Go equality (go_iface_eq)
		}
		fmt.Fprintf(&b, "#ifndef CVF_FN_%s\n#define CVF_FN_%s\nGO_MAP_FUNCS(%s, %s, %s, %s)\n#endif\n", n, n, n, k, v, sk)
	}
	b.WriteString("#endif\n")
	os.WriteFile(os.Args[3], []byte(b.String()), 0o644)
}

func fmtFloat(f float64) string {
	s := fmt.Sprintf("%v", f)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func isPkgNamed(t types.Type) (string, bool) {
	if t != nil {
		t = types.Unalias(t)
	}
	if n, ok := t.(*types.Named); ok && ownPkgs[n.Obj().Pkg()] {
		if n.Obj().Pkg() != pkg && n.Obj().Parent() != n.Obj().Pkg().Scope() {
			return "", false // function-local type of another package: gotoc hoists it
		}
		name := ownTypeName(n)
		typeByName[name] = n
		return name, true
	}
	return "", false
}

func lookupT(n string) types.Type {
	if t, ok := typeByName[n]; ok {
		return t
	}
	if tn, ok := pkg.Scope().Lookup(n).(*types.TypeName); ok {
		return tn.Type()
	}
	return nil
}

func namedDeps(t types.Type) []string {
	var out []string
	var walk func(t types.Type)
	seen := map[types.Type]bool{}
	walk = func(t types.Type) {
		if seen[t] {
			return
		}
		seen[t] = true
		if n, ok := isPkgNamed(t); ok {
			out = append(out, n)
			return
		}
		switch u := t.(type) {
		case *types.Pointer:
			walk(u.Elem())
		case *types.Array:
			walk(u.Elem())
		case *types.Slice:
			walk(u.Elem())
		case *types.Map:
			walk(u.Key())
			walk(u.Elem())
		case *types.Struct:
			for i := 0; i < u.NumFields(); i++ {
				walk(u.Field(i).Type())
			}
		}
	}
	walk(t)
	return out
}

func valueDeps(t types.Type) []string {
	var out []string
	switch u := t.(type) {
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			out = append(out, valueDepsField(u.Field(i).Type())...)
		}
	default:
		out = append(out, valueDepsField(t)...)
	}
	return out
}

func valueDepsField(t types.Type) []string {
	if n, ok := isPkgNamed(t); ok {
		return []string{n}
	}
	switch u := t.(type) {
	case *types.Array:
		return valueDepsField(u.Elem())
	case *types.Struct:
		var out []string
		for i := 0; i < u.NumFields(); i++ {
			out = append(out, valueDepsField(u.Field(i).Type())...)
		}
		return out
	case *types.Slice:
		// slice typedefs need the element type declared (typedef only)
		return nil
	}
	return nil
}

var sliceTypes = map[string]types.Type{}
var mapTypes = map[string]*types.Map{}
var arrTypes = map[string]*types.Array{}
var overrides = map[string]string{}

func mangle(t types.Type) string {
	s := cbase(t)
	r := strings.NewReplacer("*", "Ptr", " ", "", "/", "", "[", "", "]", "", ".", "_")
	if i := strings.Index(s, " /*"); i >= 0 {
		s = s[:i] + "_" + strings.Trim(r.Replace(s[i+3:]), "*")
	}
	return r.Replace(s)
}

var arrEmitted = map[string]bool{}

// ensureArrs emits the struct wrappers of array types used by a field
// (Go arrays are values: wrapping them gives C the same copy semantics).
var anonEmitted = map[string]bool{}

func ensureAnon(bb *strings.Builder, t types.Type) {
	st, ok := t.(*types.Struct)
	if !ok {
		if a, ok2 := t.(*types.Array); ok2 {
			ensureAnon(bb, a.Elem())
		}
		return
	}
	n := anonName(st)
	if anonEmitted[n] {
		return
	}
	anonEmitted[n] = true
	for i := 0; i < st.NumFields(); i++ {
		ensureAnon(bb, st.Field(i).Type())
		ensureArrs(bb, st.Field(i).Type())
	}
	fmt.Fprintf(bb, "struct %s {\n", n)
	writeFields(bb, st)
	bb.WriteString("};\n")
}

// writeFields: struct members. Embedded structs become a union of the whole
// embedded value (E_) and an anonymous struct of its fields, so both
// s.E_ and the promoted s.field work.
func writeFields(bb *strings.Builder, u *types.Struct) {
	prom := promotedNames(u)
	for i := 0; i < u.NumFields(); i++ {
		f := u.Field(i)
		name := f.Name()
		if f.Embedded() {
			if es, ok := f.Type().Underlying().(*types.Struct); ok {
				fmt.Fprintf(bb, "    union {\n        %s %s_;\n        struct {\n", cbase(f.Type()), name)
				for k := 0; k < es.NumFields(); k++ {
					fn := cField(es.Field(k).Name())
					if !prom[es.Field(k).Name()] {
						fn = fmt.Sprintf("_sh%d_%s", i, es.Field(k).Name())
					}
					fmt.Fprintf(bb, "            %s;\n", cdecl(es.Field(k).Type(), fn))
				}
				if es.NumFields() == 0 {
					bb.WriteString("            char _empty_" + name + ";\n")
				}
				bb.WriteString("        };\n    };\n")
				continue
			}
			name = "embed_" + name
		}
		fmt.Fprintf(bb, "    %s;\n", cdecl(f.Type(), cField(name)))
	}
	if u.NumFields() == 0 {
		bb.WriteString("    char _empty;\n")
	}
}

func ensureArrs(bb *strings.Builder, t types.Type) {
	a, ok := t.(*types.Array)
	if !ok {
		if _, named := isPkgNamed(t); !named {
			if a2, ok2 := t.Underlying().(*types.Array); ok2 {
				a, ok = a2, true
			}
		}
	}
	if !ok {
		return
	}
	ensureAnon(bb, a.Elem())
	ensureArrs(bb, a.Elem())
	n := cbase(a)
	if arrEmitted[n] {
		return
	}
	arrEmitted[n] = true
	fmt.Fprintf(bb, "#ifndef CVF_BODY_%s\n#define CVF_BODY_%s\nstruct %s { %s v[%d]; };\n#endif\n", n, n, n, cbase(a.Elem()), a.Len())
}

func cbase(t types.Type) string {
	if t != nil {
		t = types.Unalias(t)
	}
	if n, ok := isPkgNamed(t); ok {
		if o, ok := overrides[n]; ok {
			return o
		}
		return n
	}
	switch u := t.(type) {
	case *types.Basic:
		switch u.Kind() {
		case types.Bool:
			return "bool"
		case types.Int8:
			return "i8"
		case types.Int16:
			return "i16"
		case types.Int32:
			return "i32"
		case types.Int64:
			return "i64"
		case types.Int:
			return "int"
		case types.Uint8:
			return "u8"
		case types.Uint16:
			return "u16"
		case types.Uint32:
			return "u32"
		case types.Uint64:
			return "u64"
		case types.Uint, types.Uintptr:
			return "uintptr_t"
		case types.Float32:
			return "f32"
		case types.Float64:
			return "f64"
		case types.String:
			return "GoString"
		case types.UnsafePointer:
			return "void*"
		}
	case *types.Pointer:
		return cbase(u.Elem()) + "*"
	case *types.Slice:
		n := "Slice_" + mangle(u.Elem())
		sliceTypes[n] = u.Elem()
		return n
	case *types.Map:
		n := "Map_" + mangle(u.Key()) + "_" + mangle(u.Elem())
		mapTypes[n] = u
		return n
	case *types.Interface:
		return "GoIface"
	case *types.Signature:
		return "GoFunc"
	case *types.Array:
		n := fmt.Sprintf("Arr%d_%s", u.Len(), mangle(u.Elem()))
		arrTypes[n] = u
		return n
	case *types.Named:
		switch u.Underlying().(type) {
		case *types.Interface:
			return "GoIface"
		case *types.Basic, *types.Pointer, *types.Slice, *types.Map, *types.Signature:
			return cbase(u.Underlying())
		}
		// standard-library structs with C layouts in ik_rt_types.h (as gotoc's
		// extStructs); referenced through pointers here, so the tag suffices
		if c, ok := genExtStructs[types.TypeString(u, func(p *types.Package) string { return p.Name() })]; ok {
			return "struct " + c
		}
		return "GoOpaque /* " + types.TypeString(u, qual) + " */"
	case *types.Chan:
		return "GoChan*"
	case *types.Struct:
		n := anonName(u)
		return n
	}
	return "GoOpaque /* " + t.String() + " */"
}

func qual(p *types.Package) string {
	if p == pkg {
		return ""
	}
	return p.Name()
}

func cdecl(t types.Type, name string) string {
	return cbase(t) + " " + name
}

func isStringT(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Info()&types.IsString != 0
}

var anonStructs = map[string]*types.Struct{}
var anonOrder []string

func anonName(st *types.Struct) string {
	key := types.TypeString(st, qual)
	h := uint32(2166136261)
	for i := 0; i < len(key); i++ {
		h = (h ^ uint32(key[i])) * 16777619
	}
	n := fmt.Sprintf("Anon_%08x", h)
	if _, ok := anonStructs[n]; !ok {
		anonStructs[n] = st
		anonOrder = append(anonOrder, n)
	}
	return n
}

func cField(name string) string {
	switch name {
	case "char", "int", "float", "double", "long", "short", "signed", "unsigned", "auto", "register", "static", "extern", "volatile", "const", "struct", "union", "enum", "typedef", "sizeof", "default", "case", "do", "while", "for", "if", "else", "switch", "break", "continue", "return", "goto", "void", "inline", "restrict", "bool", "true", "false":
		return name + "_"
	}
	return name
}

// promotedNames: names of embedded structs' fields that Go promotes into
// st (not shadowed by a direct field, not present in two embeddings).
// Others keep their slot in the flattened layout under a private name.
func promotedNames(st *types.Struct) map[string]bool {
	direct := map[string]bool{}
	count := map[string]int{}
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		direct[f.Name()] = true
		if es, ok := f.Type().Underlying().(*types.Struct); ok && f.Embedded() {
			for k := 0; k < es.NumFields(); k++ {
				count[es.Field(k).Name()]++
			}
		}
	}
	out := map[string]bool{}
	for n, c := range count {
		if c == 1 && !direct[n] {
			out[n] = true
		}
	}
	return out
}

var genExtStructs = map[string]string{
	"reflect.SliceHeader":  "GoReflectSliceHeader",
	"reflect.StringHeader": "GoReflectStringHeader",
}
