// gencdefs: emit C declarations (constants, structs) for Ikemen GO types,
// using go/types. usage: gencdefs SRCDIR OUT_CONSTS OUT_TYPES Type1 Type2 ...
package main

import (
	"fmt"
	"go/ast"
	"go/build"
	"go/constant"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var pkg *types.Package

func main() {
	dir := os.Args[1]
	ctx := build.Default
	ctx.BuildTags = []string{"vita"}
	bp, _ := ctx.ImportDir(dir, 0)
	fset := token.NewFileSet()
	var files []*ast.File
	for _, f := range append(bp.GoFiles, bp.CgoFiles...) {
		af, err := parser.ParseFile(fset, filepath.Join(dir, f), nil, 0)
		if err == nil {
			files = append(files, af)
		}
	}
	conf := types.Config{FakeImportC: true, Importer: importer.ForCompiler(fset, "source", nil), Error: func(error) {}}
	pkg, _ = conf.Check("main", fset, files, nil)

	// ---- constants
	var cs []string
	sc := pkg.Scope()
	names := sc.Names()
	sort.Strings(names)
	for _, n := range names {
		c, ok := sc.Lookup(n).(*types.Const)
		if !ok {
			continue
		}
		if strings.HasPrefix(n, "OC_") {
			continue // opcodes.h
		}
		v := c.Val()
		switch v.Kind() {
		case constant.Int:
			if i, ok := constant.Int64Val(v); ok {
				if i >= -2147483648 && i <= 2147483647 {
					cs = append(cs, fmt.Sprintf("#define %s (%d)", n, i))
				} else {
					cs = append(cs, fmt.Sprintf("#define %s ((i64)%dLL)", n, i))
				}
			} else if u, ok := constant.Uint64Val(v); ok {
				cs = append(cs, fmt.Sprintf("#define %s ((u64)%dULL)", n, u))
			}
		case constant.Float:
			f, _ := constant.Float64Val(v)
			cs = append(cs, fmt.Sprintf("#define %s (%s)", n, fmtFloat(f)))
		}
	}
	out := "// Generated by tools/gen/gencdefs from Ikemen GO. Do not edit.\n#ifndef CVF_GEN_CONSTS_H\n#define CVF_GEN_CONSTS_H\n\n" + strings.Join(cs, "\n") + "\n\n#endif\n"
	os.WriteFile(os.Args[2], []byte(out), 0o644)

	// ---- types
	if b, err := os.ReadFile(os.Getenv("GENCDEFS_OVERRIDES")); err == nil {
		for _, ln := range strings.Split(string(b), "\n") {
			f := strings.Fields(ln)
			if len(f) >= 2 && !strings.HasPrefix(ln, "#") {
				overrides[f[0]] = strings.Join(f[1:], " ")
			}
		}
	}
	want := os.Args[4:]
	emitted := map[string]bool{}
	var order []string
	var visit func(n string)
	deps := map[string][]string{}
	for len(want) > 0 {
		n := want[0]
		want = want[1:]
		if emitted[n] {
			continue
		}
		emitted[n] = true
		if _, ok := overrides[n]; ok {
			continue
		}
		obj := sc.Lookup(n)
		if obj == nil {
			fmt.Fprintln(os.Stderr, "no type", n)
			continue
		}
		order = append(order, n)
		if st, ok := obj.Type().Underlying().(*types.Struct); ok {
			for i := 0; i < st.NumFields(); i++ {
				for _, d := range namedDeps(st.Field(i).Type()) {
					deps[n] = append(deps[n], d)
					want = append(want, d)
				}
			}
		} else {
			for _, d := range namedDeps(obj.Type().Underlying()) {
				deps[n] = append(deps[n], d)
				want = append(want, d)
			}
		}
	}
	_ = visit
	// topological order by value-embedding (pointers don't need order)
	done := map[string]bool{}
	var sorted []string
	var topo func(n string)
	topo = func(n string) {
		if done[n] {
			return
		}
		done[n] = true
		obj := sc.Lookup(n)
		if obj != nil {
			for _, d := range valueDeps(obj.Type().Underlying()) {
				topo(d)
			}
		}
		sorted = append(sorted, n)
	}
	sort.Strings(order)
	for _, n := range order {
		topo(n)
	}
	var keep []string
	for _, n := range sorted {
		if _, ok := overrides[n]; !ok {
			keep = append(keep, n)
		}
	}
	sorted = keep
	var b strings.Builder
	b.WriteString("// Generated by tools/gen/gencdefs from Ikemen GO. Do not edit.\n#ifndef CVF_GEN_TYPES_H\n#define CVF_GEN_TYPES_H\n\n#include \"core/gort.h\"\n\n")
	for _, n := range sorted {
		obj := sc.Lookup(n)
		if _, ok := obj.Type().Underlying().(*types.Struct); ok {
			fmt.Fprintf(&b, "typedef struct %s %s;\n", n, n)
		}
	}
	b.WriteString("\n")
	var body strings.Builder
	bb := &body
	var plainNamed, sliceNamed []string
	for _, n := range sorted {
		obj := sc.Lookup(n)
		switch u := obj.Type().Underlying().(type) {
		case *types.Struct:
			fmt.Fprintf(bb, "struct %s {\n", n)
			for i := 0; i < u.NumFields(); i++ {
				f := u.Field(i)
				name := f.Name()
				if f.Embedded() {
					// Promoted fields: anonymous struct inside a union with the
					// whole embedded value (both c.X and c.Embedded work).
					if es, ok := f.Type().Underlying().(*types.Struct); ok {
						fmt.Fprintf(bb, "    union {\n        %s %s;\n        struct {\n", cbase(f.Type()), name)
						for k := 0; k < es.NumFields(); k++ {
							fmt.Fprintf(bb, "            %s;\n", cdecl(es.Field(k).Type(), es.Field(k).Name()))
						}
						bb.WriteString("        };\n    };\n")
						continue
					}
					name = "embed_" + name
				}
				fmt.Fprintf(bb, "    %s;\n", cdecl(f.Type(), name))
			}
			if u.NumFields() == 0 {
				bb.WriteString("    char _empty;\n")
			}
			bb.WriteString("};\n\n")
		default:
			if _, isSlice := u.(*types.Slice); isSlice {
				sliceNamed = append(sliceNamed, fmt.Sprintf("typedef %s;\n", cdecl(u, n)))
			} else {
				plainNamed = append(plainNamed, fmt.Sprintf("typedef %s;\n", cdecl(u, n)))
			}
		}
	}
	var mn0 []string
	for n := range mapTypes {
		mn0 = append(mn0, n)
	}
	sort.Strings(mn0)
	for _, n := range mn0 {
		fmt.Fprintf(&b, "typedef GoMap %s; /* %s */\n", n, types.TypeString(mapTypes[n], qual))
	}
	for _, t := range plainNamed {
		b.WriteString(t)
	}
	var an []string
	for n := range arrTypes {
		an = append(an, n)
	}
	sort.Strings(an)
	for _, n := range an {
		fmt.Fprintf(&b, "typedef %s %s[%d];\n", cbase(arrTypes[n].Elem()), n, arrTypes[n].Len())
	}
	// slice and map typedefs (element types may be incomplete: pointers only)
	var sn []string
	for n := range sliceTypes {
		sn = append(sn, n)
	}
	sort.Strings(sn)
	for _, n := range sn {
		fmt.Fprintf(&b, "typedef struct { %s *p; int len, cap; } %s;\n", cbase(sliceTypes[n]), n)
	}
	for _, t := range sliceNamed {
		b.WriteString(t)
	}
	b.WriteString("\n")
	b.WriteString(body.String())
	b.WriteString("#endif\n")
	os.WriteFile(os.Args[3], []byte(b.String()), 0o644)
}

func fmtFloat(f float64) string {
	s := fmt.Sprintf("%v", f)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func isPkgNamed(t types.Type) (string, bool) {
	if n, ok := t.(*types.Named); ok && n.Obj().Pkg() == pkg {
		return n.Obj().Name(), true
	}
	return "", false
}

func namedDeps(t types.Type) []string {
	var out []string
	var walk func(t types.Type)
	seen := map[types.Type]bool{}
	walk = func(t types.Type) {
		if seen[t] {
			return
		}
		seen[t] = true
		if n, ok := isPkgNamed(t); ok {
			out = append(out, n)
			return
		}
		switch u := t.(type) {
		case *types.Pointer:
			walk(u.Elem())
		case *types.Array:
			walk(u.Elem())
		case *types.Slice:
			walk(u.Elem())
		case *types.Map:
			walk(u.Key())
			walk(u.Elem())
		case *types.Struct:
			for i := 0; i < u.NumFields(); i++ {
				walk(u.Field(i).Type())
			}
		}
	}
	walk(t)
	return out
}

func valueDeps(t types.Type) []string {
	var out []string
	switch u := t.(type) {
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			out = append(out, valueDepsField(u.Field(i).Type())...)
		}
	default:
		out = append(out, valueDepsField(t)...)
	}
	return out
}

func valueDepsField(t types.Type) []string {
	if n, ok := isPkgNamed(t); ok {
		return []string{n}
	}
	switch u := t.(type) {
	case *types.Array:
		return valueDepsField(u.Elem())
	case *types.Slice:
		// slice typedefs need the element type declared (typedef only)
		return nil
	}
	return nil
}

var sliceTypes = map[string]types.Type{}
var mapTypes = map[string]*types.Map{}
var arrTypes = map[string]*types.Array{}
var overrides = map[string]string{}

func mangle(t types.Type) string {
	s := cbase(t)
	r := strings.NewReplacer("*", "Ptr", " ", "", "/", "", "[", "", "]", "", ".", "_")
	if i := strings.Index(s, " /*"); i >= 0 {
		s = s[:i] + "_" + strings.Trim(r.Replace(s[i+3:]), "*")
	}
	return r.Replace(s)
}

func cbase(t types.Type) string {
	if n, ok := isPkgNamed(t); ok {
		if o, ok := overrides[n]; ok {
			return o
		}
		return n
	}
	switch u := t.(type) {
	case *types.Basic:
		switch u.Kind() {
		case types.Bool:
			return "bool"
		case types.Int8:
			return "i8"
		case types.Int16:
			return "i16"
		case types.Int32:
			return "i32"
		case types.Int64:
			return "i64"
		case types.Int:
			return "int"
		case types.Uint8:
			return "u8"
		case types.Uint16:
			return "u16"
		case types.Uint32:
			return "u32"
		case types.Uint64:
			return "u64"
		case types.Uint, types.Uintptr:
			return "uintptr_t"
		case types.Float32:
			return "f32"
		case types.Float64:
			return "f64"
		case types.String:
			return "GoString"
		}
	case *types.Pointer:
		return cbase(u.Elem()) + "*"
	case *types.Slice:
		n := "Slice_" + mangle(u.Elem())
		sliceTypes[n] = u.Elem()
		return n
	case *types.Map:
		n := "Map_" + mangle(u.Key()) + "_" + mangle(u.Elem())
		mapTypes[n] = u
		return n
	case *types.Interface:
		return "GoIface"
	case *types.Signature:
		return "GoFunc"
	case *types.Array:
		n := fmt.Sprintf("Arr%d_%s", u.Len(), mangle(u.Elem()))
		arrTypes[n] = u
		return n
	case *types.Named:
		return "GoOpaque /* " + types.TypeString(u, qual) + " */"
	case *types.Chan:
		return "GoOpaque /* chan */"
	case *types.Struct:
		return "struct { char _anon; } /* anon struct */"
	}
	return "GoOpaque /* " + t.String() + " */"
}

func qual(p *types.Package) string {
	if p == pkg {
		return ""
	}
	return p.Name()
}

func cdecl(t types.Type, name string) string {
	switch u := t.(type) {
	case *types.Array:
		var dims string
		for {
			dims += fmt.Sprintf("[%d]", u.Len())
			if e, ok := u.Elem().(*types.Array); ok {
				if _, named := isPkgNamed(u.Elem()); !named {
					u = e
					continue
				}
			}
			break
		}
		return cbase(u.Elem()) + " " + name + dims
	}
	if _, ok := isPkgNamed(t); !ok {
		if a, ok := t.Underlying().(*types.Array); ok && t == t.Underlying() {
			return cdecl(a, name)
		}
	}
	return cbase(t) + " " + name
}
